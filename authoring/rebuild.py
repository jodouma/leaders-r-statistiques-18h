"""Rebuild this edition from its editable sources (maintainers only).

From the repository: pip install -r authoring/requirements.txt
Then: python authoring/rebuild.py
Use --r /path/to/Rscript or --out /path/to/pdf to override the defaults.
RStudio screenshots are genuine captured assets, not generated by this build.
Students only need the supplied PDFs, CSV files and R/RStudio, not Python.
"""
import argparse
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--r', default='Rscript', help='Rscript executable')
    parser.add_argument('--out', default=str(ROOT / 'pdf'))
    args = parser.parse_args()

    # Separate R processes prevent a previous script's objects from hiding errors.
    for script in sorted((ROOT / 'scripts').glob('[0-9][0-9]_*.R')):
        subprocess.run([args.r, '--vanilla', str(script)], cwd=ROOT, check=True)

    # Facts come from those actual exports, diagrams from the same source data,
    # and the composer derives the printed contents from the final pagination.
    for name in ('build_finance_manifest.py', 'visuals_finance.py', 'compose_finance.py'):
        subprocess.run([sys.executable, str(ROOT / 'authoring' / name)], cwd=ROOT, check=True)
    subprocess.run([sys.executable, str(ROOT / 'authoring/build_pdfs.py'),
                    str(ROOT / 'authoring/content_finance.json'), '--out', args.out],
                   cwd=ROOT, check=True)


if __name__ == '__main__':
    main()
